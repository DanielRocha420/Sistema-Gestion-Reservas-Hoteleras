CREATE TABLE HUESPEDES (
    ID_HUESPED NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(50) NOT NULL,
    APELLIDO_MATERNO VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(50) NOT NULL,
    TELEFONO VARCHAR2(10) NOT NULL,
    DOCUMENTO VARCHAR2(50) NOT NULL,
    TIPO_DOCUMENTO VARCHAR(30) NOT NULL,
    NACIONALIDAD VARCHAR2(50) NOT NULL,
    ESTADO VARCHAR(30) NOT NULL,
    CONSTRAINT HUESPED_PK PRIMARY KEY(ID_HUESPED),
    CONSTRAINT HUESPED_EMAIL_UK UNIQUE(EMAIL),
    CONSTRAINT HUESPED_TELEFONO_UK UNIQUE(TELEFONO),
    CONSTRAINT HUESPED_TEL_CHK CHECK(REGEXP_LIKE(TELEFONO, '^[0-9]{10}$')),
    CONSTRAINT HUESPED_DOCUMENTO_UK UNIQUE(DOCUMENTO),
    CONSTRAINT HUESPED_CHK CHECK (TIPO_DOCUMENTO IN('INE','PASAPORTE','LICENCIA_CONDUCIR','CEDULA_PROFESIONAL' )),
    CONSTRAINT HUESPED_ESTADO_CHK (ESTADO IN('ACTIVO', 'ELIMINADO'))
);

CREATE TABLE HABITACION(
    ID_HABITACION NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    TIPO VARCHAR2(50) NOT NULL,
    PRECIO NUMBER(10, 2) NOT NULL,
    CAPACIDAD NUMBER(10) NOT NULL,
    ESTADO VARCHAR2(30) NOT NULL,
    CONSTRAINT HABITACION_PK PRIMARY KEY(ID_HABITACION),
    CONSTRAINT HABITACION_CHK CHECK (ESTADO IN('DISPONIBLE', 'OCUPADA', 'LIMPIEZA', 'MANTENIMIENTO')),
    CONSTRAINT HABITACION_TIPO_CHK CHECK (TIPO IN('INDIVIDUAL', 'DOBLE', 'FAMILIAR'))
);

CREATE TABLE RESERVA(
    ID_RESERVA NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ESTADO_RESERVA VARCHAR(50) NOT NULL,
    FECHA_ENTRADA DATE,
    FECHA_SALIDA DATE,
    CONSTRAINT RESERVA_PK PRIMARY KEY(ID_RESERVA),
    CONSTRAINT RESERVA_CHK CHECK (ESTADO_RESERVA IN('CONFIRMADA', 'EN_CURSO', 'FINALIZADA', 'CANCELADA'))
);